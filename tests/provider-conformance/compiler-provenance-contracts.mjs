import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile,mkdtemp,mkdir,writeFile,copyFile,symlink,rm,access} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const root=fileURLToPath(new URL('../../',import.meta.url));

test('every provider machine module is compiled from its TypeScript source',async()=>{
 const config=JSON.parse(await readFile(path.join(root,'licensing/provider-packages.json')));
 assert.deepEqual(config.playerCoreSources.filter(file=>file.startsWith('web/generated/')),[],'core sources overwrite freshly compiled output with cached generated code');
 let modules=0;
 for(const [name,profile] of Object.entries(config.profiles)){
  assert.deepEqual(profile.files.filter(file=>file.startsWith('web/generated/internal/machine/')),[],name+' copies cached machine output');
  assert.equal(new Set(profile.generated).size,profile.generated.length,name+' duplicates compiler outputs');
  for(const file of profile.generated.filter(file=>file.startsWith('web/generated/internal/machine/'))){
   assert.ok(!profile.files.includes(file),name+' has two authorities for '+file);
   await access(path.join(root,file.replace('web/generated/','src/').replace(/\.js$/,'.ts')));modules++;
  }
 }
 assert.ok(modules>0,'fixture must exercise actual shared machine modules');
});

test('core and provider compilers ignore stale generated bytes and preserve the same source provenance',async t=>{
 const fixture=await mkdtemp(path.join(tmpdir(),'demuxe-compiler-provenance-'));
 t.after(()=>rm(fixture,{recursive:true,force:true}));
 for(const directory of ['scripts','licensing','src/internal/machine','web/generated/internal/machine','packages/player-core'])await mkdir(path.join(fixture,directory),{recursive:true});
 for(const name of ['compile-player-package.mjs','compile-provider-sources.mjs'])await copyFile(path.join(root,'scripts',name),path.join(fixture,'scripts',name));
 await symlink(path.join(root,'node_modules'),path.join(fixture,'node_modules'),'dir');
 const source='src/internal/machine/shared.ts',output='web/generated/internal/machine/shared.js';
 // The initial type is erased, which also erases its attached SPDX comment.
 // A checked-in generated file with that comment must not replace fresh output.
 await writeFile(path.join(fixture,source),'// SPDX-License-Identifier: Apache-2.0\nexport type Input = number;\nexport const value = 7;\n');
 await writeFile(path.join(fixture,'src/internal/provider-build.ts'),'export const providerDeploymentEnabled = false;\n');
 await writeFile(path.join(fixture,output),'// SPDX-License-Identifier: Apache-2.0\nexport const value = 999;\n');
 await writeFile(path.join(fixture,'tsconfig.json'),JSON.stringify({compilerOptions:{target:'ES2022',module:'ES2022',moduleResolution:'bundler',strict:true,declaration:true,rootDir:'src',outDir:'web/generated',skipLibCheck:true},include:['src/**/*.ts']}));
 await writeFile(path.join(fixture,'licensing/provider-packages.json'),JSON.stringify({playerCoreSources:[source],playerCoreComputedImports:{},profiles:{fixture:{generated:[output]}}}));
 await writeFile(path.join(fixture,'licensing/provider-runtime-qualification.json'),JSON.stringify({schema:1,status:'candidate',providers:{}}));
 await writeFile(path.join(fixture,'packages/player-core/package.json'),JSON.stringify({exports:{'.':{import:'./'+output,types:'./'+output.replace(/\.js$/,'.d.ts')}}}));
 const invoke=(script,args=[])=>JSON.parse(execFileSync(process.execPath,['scripts/'+script,...args],{cwd:fixture,env:{...process.env,DEMUXE_PROVIDER_CANDIDATE:'1'},maxBuffer:1024*1024,encoding:'utf8',stdio:['ignore','pipe','pipe']}));
 const core=invoke('compile-player-package.mjs'),provider=invoke('compile-provider-sources.mjs',['fixture']);
 assert.deepEqual(core.outputs[output],provider[output]);
 assert.deepEqual(provider[output].inputs,[source]);
 assert.match(provider[output].data,/value = 7/);
 assert.doesNotMatch(provider[output].data,/999/);
 assert.notEqual(provider[output].data,await readFile(path.join(fixture,output),'utf8'));
 assert.ok(core.sources[source]?.sha256);
 const config=JSON.parse(await readFile(path.join(fixture,'licensing/provider-packages.json')));
 config.playerCoreSources.push(output);
 await writeFile(path.join(fixture,'licensing/provider-packages.json'),JSON.stringify(config));
 assert.throws(()=>invoke('compile-player-package.mjs'),error=>error.status!==0&&error.stderr.includes('Cached generated output is not a core source: '+output));
});
